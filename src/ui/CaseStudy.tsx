import { useEffect, useRef, useState } from 'react'
import { clsx } from 'clsx'
import { projects } from '../data/studio'

interface Props {
  slug: string
  onClose: () => void
  onNav: (slug: string) => void
}

/** Full case study: real screenshots (and the real generated video for Lumora), architecture, decisions, honest limitations. */
export function CaseStudy({ slug, onClose, onNav }: Props) {
  const idx = Math.max(0, projects.findIndex((p) => p.slug === slug))
  const p = projects[idx]
  const prev = projects[(idx - 1 + projects.length) % projects.length]
  const next = projects[(idx + 1) % projects.length]
  const root = useRef<HTMLDivElement>(null)
  const [shown, setShown] = useState(false)
  const [videoFailed, setVideoFailed] = useState(false)

  useEffect(() => {
    const t = requestAnimationFrame(() => setShown(true))
    return () => cancelAnimationFrame(t)
  }, [])

  useEffect(() => {
    root.current?.scrollTo({ top: 0 })
    root.current?.focus()
  }, [slug])

  const images = [
    { src: p.hero ?? p.img, caption: p.hero ? `${p.title} — in use` : `${p.title} — the live application` },
    ...(p.hero && p.img !== p.hero ? [{ src: p.img, caption: `${p.title} — landing page` }] : []),
  ]
  const video = p.links.find((l) => /video/i.test(l.label))?.href
  const status = p.live ? 'Deployed demonstration' : 'Working prototype'

  return (
    <div ref={root} tabIndex={-1} data-lenis-prevent role="dialog" aria-modal="true" aria-label={`${p.title} case study`} className={clsx('sheet', shown && 'is-in')}>
      <div className="sheet__bar">
        <button className="btn" onClick={onClose} data-cursor="Back">
          <span aria-hidden>←</span> Back to the journey
        </button>
        <span className="sheet__count hide-sm">
          Case study {p.index} / 04 — {p.title}
        </span>
        <a className="btn btn--primary" href={p.live ?? p.repo} target="_blank" rel="noreferrer">
          {p.live ? 'Live demo' : 'Source'} <span aria-hidden>↗</span>
        </a>
      </div>

      <div className="sheet__inner">
        <p className="kicker">{p.discipline}</p>
        <h2 className="display" style={{ marginTop: '1rem' }}>{p.title}</h2>
        <p className="sheet__lead">{p.summary}</p>

        <dl className="facts">
          <div><dt>Type</dt><dd>{p.client}</dd></div>
          <div><dt>Year</dt><dd>{p.year}</dd></div>
          <div><dt>Status</dt><dd>{status}</dd></div>
          <div><dt>Source</dt><dd><a href={p.repo} target="_blank" rel="noreferrer" style={{ textDecoration: 'underline', textDecorationColor: 'var(--amber)', textUnderlineOffset: 5 }}>Open on GitHub ↗</a></dd></div>
        </dl>

        <div className={clsx('shots', images.length > 1 && 'shots--2')}>
          {images.map((im) => (
            <figure className="shot" key={im.src}>
              <img src={im.src} alt={`${im.caption}`} loading="lazy" />
              <figcaption>{im.caption}</figcaption>
            </figure>
          ))}
        </div>

        {video && !videoFailed && (
          <figure className="shot" style={{ marginTop: '1rem', maxWidth: '24rem' }}>
            <video controls playsInline preload="none" poster={p.hero ?? p.img} onError={() => setVideoFailed(true)} aria-label="Video generated end to end by Lumora AI">
              <source src={video} type="video/mp4" />
            </video>
            <figcaption>The real output — a 1080×1920 video generated by the pipeline.</figcaption>
          </figure>
        )}

        <div className="cols">
          <div>
            <h3>Architecture &amp; data flow</h3>
            <ol className="steps" style={{ marginTop: '1.4rem' }}>
              {p.architecture.map((n, i) => (
                <li key={n.label}>
                  <b>{String(i + 1).padStart(2, '0')}</b>
                  <div>
                    <strong>{n.label}</strong>
                    <span>{n.note}</span>
                  </div>
                </li>
              ))}
            </ol>
          </div>
          <div style={{ display: 'grid', gap: '2.6rem', alignContent: 'start' }}>
            <div>
              <h4>What it does</h4>
              <ul className="bullets">{p.features.map((f) => <li key={f}>{f}</li>)}</ul>
            </div>
            <div>
              <h4>Technical decisions</h4>
              <ul className="bullets">{p.decisions.map((f) => <li key={f}>{f}</li>)}</ul>
            </div>
            <div>
              <h4>Honest limitations</h4>
              <ul className="bullets bullets--mute">{p.limitations.map((f) => <li key={f}>{f}</li>)}</ul>
            </div>
          </div>
        </div>

        <h4 style={{ marginTop: '3.5rem' }}>Built with</h4>
        <ul className="chips" style={{ marginTop: '1rem' }}>{p.stack.map((s) => <li key={s} className="chip">{s}</li>)}</ul>

        <div className="cta-row" style={{ marginTop: '2.2rem' }}>
          {p.links.map((l, i) => (
            <a key={l.label} className={clsx('btn', i === 0 && p.live && 'btn--primary')} href={l.href} target="_blank" rel="noreferrer">
              {l.label} <span aria-hidden>↗</span>
            </a>
          ))}
        </div>

        <nav className="pager" aria-label="More case studies">
          <button onClick={() => onNav(prev.slug)}><small>← Previous</small><span>{prev.title}</span></button>
          <button onClick={() => onNav(next.slug)}><small>Next →</small><span>{next.title}</span></button>
        </nav>
      </div>
    </div>
  )
}
